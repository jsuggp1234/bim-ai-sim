// 이름 짓기 (같은 seed는 같은 이름)
export function nameFor(role, seed) {
  const R = ROLES[role] || ROLES.labor;
  if (R.foreign) { const f = FOREIGN[Math.floor(hsh(seed, 3) * FOREIGN.length) % FOREIGN.length]; return { name: pick(f.names, hsh(seed, 4)), from: f.from, home: f.home, food: f.food }; }
  const giv = R.gender === 'f' ? GIV_F : R.young ? GIV_Y : GIV_M;
  return { name: pick(SUR, hsh(seed, 1)) + pick(giv, hsh(seed, 2)) };
}

// 한 사람의 대화: { role, title, name, meta, hat, lines[] }
// ctx: { month, wpId, boss(현장소장 이름), co(회사) }
export function talkFor(role, seed, ctx = {}) {
  const key = ROLES[role] ? role : 'labor', R = ROLES[key];
  const nm = nameFor(key, seed), age = Math.round(R.age[0] + hsh(seed, 5) * (R.age[1] - R.age[0])), yrs = Math.max(1, Math.min(age - 18, Math.round(R.yrs[0] + hsh(seed, 6) * (R.yrs[1] - R.yrs[0]))));
  const pg = phaseGroup(ctx.wpId || ''), season = seasonOf(ctx.month || 5);
  const fill = (s) => s.replace(/\{(\w+)\}/g, (_, k) => ({ name: nm.name, yrs, phase: PHASE_NAME[pg], boss: ctx.boss || '', co: ctx.co || '', from: nm.from || '', home: nm.home || '', food: nm.food || '' })[k] ?? '');
  // 고충 셋을 seed 순서로 (같은 사람은 같은 순서)
  const pool = R.lines.map((l, i) => [hsh(seed, 20 + i), l]).sort((a, b) => a[0] - b[0]).map(x => x[1]);
  const lines = [pick(R.intro, hsh(seed, 7))];
  lines.push(...pool.slice(0, 3));
  // 계절 이야기 (역할에 맞는 것 먼저) → 없으면 공정 이야기
  const sk = season === 'rain' ? 'summer' : season;
  const own = R[sk] && R[sk].length ? R[sk] : null;
  if (own) lines.push(pick(own, hsh(seed, 31)));
  else if (!R.eq && hsh(seed, 32) < 0.6 && SEASON[season]) lines.push(pick(SEASON[season], hsh(seed, 33)));
  if (!R.eq && !['guard', 'traffic', 'foreign'].includes(key) && PHASE[pg] && hsh(seed, 34) < 0.7) lines.push(pick(PHASE[pg], hsh(seed, 35)));
  lines.push(pick(R.close, hsh(seed, 36)));
  const meta = [R.t, R.foreign ? nm.from + ' 출신' : null, `${age}세`, R.civ ? null : R.foreign ? `한국 ${yrs}년 차` : `경력 ${yrs}년`].filter(Boolean).join(' · ');
  return { role: key, title: R.t, name: nm.name, meta, hat: R.hat, lines: lines.map(fill) };
}

