// 장비 이름표 → 운전하는 사람의 역할 (없으면 null)
export function roleOfEquipment(name) {
  const s = String(name || '');
  if (/덤프/.test(s)) return 'dump';
  if (/레미콘/.test(s)) return 'mixer';
  if (/트레일러/.test(s)) return 'trailer';
  if (/수중펌프|진공 펌프|집수정|복공/.test(s)) return null;
  if (/펌프/.test(s)) return 'pump';
  if (/백호|굴착기(?!.*RCD)/.test(s) && !/RCD/.test(s)) return 'excav';
  if (/RCD|오거|천공|항타|해머|파일|할암|발파/.test(s)) return 'rig';
  if (/크레인|크람쉘|클램|그래브|호이스트/.test(s)) return 'crane';
  return null;
}

