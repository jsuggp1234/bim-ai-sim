function inside(poly, x, y) {
  let c = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if ((yi > y) !== (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) c = !c;
  }
  return c;
}
// 월드 좌표 SVG (atlas.setVector에 그대로)
export function koreaSVG({ step = 0.075 } = {}) {
  const pts = [];
  for (let lat = 33.05; lat < 38.7; lat += step * 0.82) for (let lng = 125.9; lng < 129.7; lng += step) {
    if (SHAPES.some(s => inside(s, lng, lat))) { const [x, y] = lngLatToWorld(lng, lat); pts.push(`M${x.toFixed(4)} ${y.toFixed(4)}h0`); }
  }
  const outline = SHAPES.map(s => 'M' + s.map(([a, b]) => lngLatToWorld(a, b).map(v => v.toFixed(4)).join(' ')).join('L') + 'Z').join('');
  // 경위도 격자 (1°)
  const grid = [];
  for (let lng = 125; lng <= 131; lng++) { const [x0, y0] = lngLatToWorld(lng, 32.6), [, y1] = lngLatToWorld(lng, 39); grid.push(`M${x0.toFixed(4)} ${y0.toFixed(4)}V${y1.toFixed(4)}`); }
  for (let lat = 33; lat <= 39; lat++) { const [x0, y0] = lngLatToWorld(124.6, lat), [x1] = lngLatToWorld(131.4, lat); grid.push(`M${x0.toFixed(4)} ${y0.toFixed(4)}H${x1.toFixed(4)}`); }
  return `<path class="kr-grid" d="${grid.join('')}"/><path class="kr-land" d="${outline}"/><path class="kr-dots" d="${pts.join('')}"/>`;
}
