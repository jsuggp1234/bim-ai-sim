const quant = (a, q) => { if (!a.length) return 0; const i = (a.length - 1) * q, lo = Math.floor(i), hi = Math.ceil(i); return a[lo] + (a[hi] - a[lo]) * (i - lo); };
export function stats(vals) {
  const a = vals.filter(Number.isFinite).sort((x, y) => x - y);
  return { n: a.length, min: a[0] ?? 0, q1: quant(a, 0.25), med: quant(a, 0.5), q3: quant(a, 0.75), max: a[a.length - 1] ?? 0 };
}

